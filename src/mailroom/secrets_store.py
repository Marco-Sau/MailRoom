"""Secret storage.

Primary backend is the macOS Keychain via `keyring`. Nothing is ever written to
disk in plaintext and secrets are never logged or returned by the API - the API
only ever reports presence/absence.
"""
from __future__ import annotations

import logging
from typing import Iterable

import keyring
from keyring.errors import KeyringError

from .settings import settings

log = logging.getLogger(__name__)

# Canonical secret keys the app knows about.
SECRET_KEYS: dict[str, str] = {
    "anthropic_api_key": "Anthropic API key",
    "openai_api_key": "OpenAI API key",
    "gemini_api_key": "Google AI Studio (Gemini) API key",
    "n8n_api_key": "n8n API key",
    "n8n_webhook_key": "n8n webhook key (generated by the app)",
    "google_client_secret_json": "Google OAuth desktop client JSON",
    "google_token_json": "Google OAuth refresh token bundle",
}

# Secrets the app creates itself. They are never typed in, so the Settings form
# does not offer an input for them.
GENERATED_KEYS: frozenset[str] = frozenset({"n8n_webhook_key"})


class SecretStore:
    def __init__(self, service: str | None = None) -> None:
        self.service = service or settings.keyring_service

    def set(self, key: str, value: str) -> None:
        if key not in SECRET_KEYS:
            raise KeyError(f"unknown secret key: {key}")
        keyring.set_password(self.service, key, value)

    def get(self, key: str) -> str | None:
        try:
            return keyring.get_password(self.service, key)
        except KeyringError as exc:  # locked keychain, no backend, etc.
            log.warning("keyring read failed for %s: %s", key, exc)
            return None

    def require(self, key: str) -> str:
        val = self.get(key)
        if not val:
            raise RuntimeError(
                f"Missing secret '{key}'. Add it in Settings before running this job."
            )
        return val

    def delete(self, key: str) -> None:
        try:
            keyring.delete_password(self.service, key)
        except KeyringError:
            pass

    def status(self, keys: Iterable[str] | None = None) -> dict[str, bool]:
        return {k: bool(self.get(k)) for k in (keys or SECRET_KEYS)}


store = SecretStore()
