class SecretIn(BaseModel):
    key: str
    value: str


@router.get("/status")
def status():
    return {
        "secrets": store.status(),
        "secret_labels": {k: v for k, v in SECRET_KEYS.items() if k not in GENERATED_KEYS},
        "google": google_auth.status(),
        "providers": list(PROVIDERS),
        "rules_loaded": bool(Rules.load().raw),
    }


@router.post("/secrets")
def set_secret(payload: SecretIn):
    if payload.key not in SECRET_KEYS:
        raise HTTPException(400, f"unknown secret key {payload.key}")
    if payload.key in GENERATED_KEYS:
        raise HTTPException(400, f"{payload.key} is generated by the app; use Settings → Advanced → Webhook key")
    store.set(payload.key, payload.value)
    return {"ok": True, "key": payload.key}


@router.delete("/secrets/{key}")
def delete_secret(key: str):
    store.delete(key)
    return {"ok": True}


