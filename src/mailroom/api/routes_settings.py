# ------------------------------------------------------------------ legacy rules.yaml (Advanced)
class RulesIn(BaseModel):
    text: str


@router.get("/rules-yaml")
def rules_yaml_get():
    from ..settings import settings
    p = settings.rules_path
    return {"text": p.read_text(encoding="utf-8"), "file": p.name}


@router.put("/rules-yaml")
def rules_yaml_put(payload: RulesIn):
    """Replace config/rules.yaml after checking it parses; the previous file is kept as a backup."""
    import time

    import yaml

    from ..settings import settings
    try:
        data = yaml.safe_load(payload.text)
    except yaml.YAMLError as exc:
        mark = getattr(exc, "problem_mark", None)
        where = f" (line {mark.line + 1}, column {mark.column + 1})" if mark else ""
        raise HTTPException(400, f"Not valid YAML{where}: {getattr(exc, 'problem', exc)}") from exc
    if not isinstance(data, dict):
        raise HTTPException(400, "The file must be a set of named sections (identity:, categories:, ...).")
    target = settings.config_dir / "rules.yaml"
    if target.exists():
        backup = settings.data_dir / f"rules.yaml.bak-{time.strftime('%Y%m%d%H%M%S')}"
        backup.write_text(target.read_text(encoding="utf-8"), encoding="utf-8")
    target.write_text(payload.text if payload.text.endswith("\n") else payload.text + "\n", encoding="utf-8")
    return {"ok": True, "file": target.name}
