# ---------------------------------------------------------- webhook key
class WebhookKeyIn(BaseModel):
    job_id: str | None = None     # default: the first n8n job in jobs.yaml
    allow_unpublished: bool = False


def _n8n_job(job_id: str | None):
    from ..jobs import load_jobs
    jobs = [j for j in load_jobs() if j.runner == "n8n" and j.webhook_url]
    if job_id:
        jobs = [j for j in jobs if j.job_id == job_id]
    if not jobs:
        raise HTTPException(404, "no n8n job with a webhook_url in config/jobs.yaml")
    return jobs[0]


@router.get("/n8n/webhook-key")
def webhook_key_status(job_id: str | None = None):
    from ..connectors import n8n_webhook_key as wk
    st = wk.status()
    try:
        job = _n8n_job(job_id)
        st.update({"job_id": job.job_id, "job_name": job.name, "job_auth": job.auth,
                   "webhook_url": job.webhook_url})
    except HTTPException:
        pass
    return st


@router.post("/n8n/webhook-key")
def webhook_key_create(payload: WebhookKeyIn):
    """Create or rotate the key, store it in the Keychain and require it on the
    job's webhook. The key itself is never returned."""
    from ..connectors import n8n_webhook_key as wk
    job = _n8n_job(payload.job_id)
    path = job.webhook_url.split("/webhook/", 1)[-1].strip("/")
    try:
        wid = wk.find_workflow_by_path(path)
        out = wk.secure_webhook(wid, path, allow_unpublished=payload.allow_unpublished)
    except wk.UnpublishedChanges as exc:
        raise HTTPException(409, f"UNPUBLISHED: {exc}") from exc
    except Exception as exc:  # noqa: BLE001
        raise HTTPException(502, f"{type(exc).__name__}: {exc}") from exc
    out["job_auth"] = job.auth
    if job.auth != "key":
        out["note"] = (f"Set `auth: key` on job '{job.job_id}' in config/jobs.yaml, "
                       f"otherwise the Run button will be refused by n8n.")
    return out


