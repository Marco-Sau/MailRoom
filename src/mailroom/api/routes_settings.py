# ---------------------------------------------------------------- appearance
class UIPrefs(BaseModel):
    theme: str | None = None              # auto (follow macOS) | light | dark
    lookbackHours: int | None = None      # Run tab: 0 = standard windows, else 1-168 hours
    showAdvanced: bool | None = None      # Settings: Advanced group open


def _ui_path():
    from ..settings import settings
    return settings.data_dir / "ui.json"


def _ui_read() -> dict:
    import json
    try:
        data = json.loads(_ui_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        data = {}
    theme = data.get("theme") if data.get("theme") in ("auto", "light", "dark") else "auto"
    lb = data.get("lookbackHours")
    lb = lb if isinstance(lb, int) and 0 <= lb <= 168 else 0
    return {"theme": theme, "lookbackHours": lb, "showAdvanced": data.get("showAdvanced") is True}


@router.get("/ui")
def ui_get():
    return _ui_read()


@router.put("/ui")
def ui_put(payload: UIPrefs):
    import json
    cur = _ui_read()
    if payload.theme is not None:
        if payload.theme not in ("auto", "light", "dark"):
            raise HTTPException(400, "theme must be auto, light or dark")
        cur["theme"] = payload.theme
    if payload.lookbackHours is not None:
        if not 0 <= payload.lookbackHours <= 168:
            raise HTTPException(400, "lookbackHours must be 0 (standard) or 1-168")
        cur["lookbackHours"] = payload.lookbackHours
    if payload.showAdvanced is not None:
        cur["showAdvanced"] = payload.showAdvanced
    p = _ui_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(cur), encoding="utf-8")
    return cur


